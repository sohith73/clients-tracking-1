import { Router } from "express";
import { requireActiveUser, verifyAdmin } from "./requireActiveUser.js";
import * as endpoint0 from "./endpoints/today.js";
import * as endpoint1 from "./endpoints/checkIn.js";
import * as endpoint2 from "./endpoints/checkOut.js";
import * as endpoint3 from "./endpoints/month.js";
import * as endpoint4 from "./endpoints/leaves.js";
import * as endpoint5 from "./endpoints/cancelLeave.js";
import * as endpoint6 from "./endpoints/overview.js";
import * as endpoint7 from "./endpoints/adminLeaves.js";
import * as endpoint8 from "./endpoints/decideLeave.js";
import * as endpoint9 from "./endpoints/adminAttendance.js";
import * as endpoint10 from "./endpoints/adminSettings.js";
import * as people from "./endpoints/people.js";
import * as holidays from "./endpoints/holidays.js";
export const attendanceRouter = Router();
const router = attendanceRouter;
router.use(requireActiveUser);
router.get("/today", endpoint0.GET);
router.post("/check-in", endpoint1.POST);
router.post("/check-out", endpoint2.POST);
router.get("/month", endpoint3.GET);
router.get("/holidays", holidays.GET);
router.get("/leaves", endpoint4.GET);
router.post("/leaves", endpoint4.POST);
router.post("/leaves/:id/cancel", endpoint5.POST);
router.get("/admin/overview", verifyAdmin, endpoint6.GET);
router.get("/admin/leaves", verifyAdmin, endpoint7.GET);
router.patch("/admin/leaves/:id", verifyAdmin, endpoint8.PATCH);
router.get("/admin/attendance", verifyAdmin, endpoint9.GET);
router.put("/admin/attendance", verifyAdmin, endpoint9.PUT);
router.get("/admin/settings", verifyAdmin, endpoint10.GET);
router.put("/admin/settings", verifyAdmin, endpoint10.PUT);
router.get("/admin/people", verifyAdmin, people.GET);
router.post("/admin/people", verifyAdmin, people.POST);
router.patch("/admin/people/:id", verifyAdmin, people.PATCH);
router.post("/admin/people/:id/reset-password", verifyAdmin, people.RESET_PASSWORD);
